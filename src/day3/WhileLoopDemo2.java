//Problem statement: Write a program to display your name 5 times
package day3;

public class WhileLoopDemo2 {

	public static void main(String[] args) {
	
		
		int i=1;	//Initialisation
		
		while(i<=5)
		{
			System.out.println("Virat Kohli " + i);
			
			i=i+2;
		}
	}

}


/* output 
Virat Kohli 1

Virat Kohli 3

Virat Kohli 5

*/